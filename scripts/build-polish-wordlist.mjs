/**
 * Generates src/lib/polish-words.mjs: the vocabulary translation-guard.mjs
 * uses to spot Polish left behind in "English" product names.
 *
 *   npx dotenv run -f .env.local -- node scripts/build-polish-wordlist.mjs
 *
 * Derived from data instead of a hand-written list (the hand-written one
 * missed "lampa", "stalowa", "zasilacz", …). A word counts as Polish when:
 *
 *  - it occurs in the Polish source names of the pl -> en `translations`;
 *  - it never occurs in genuinely English text — Maxy's feed is English at
 *    the source, ~3.5M characters of it, which serves as the reference; and
 *  - the first translation pass usually *did* translate it. Brand names
 *    ("Lahti", "Proline") are also absent from Maxy's English but were always
 *    carried over unchanged, so they fail this test and stay off the list.
 *
 * Comparing against the English side of the pairs alone does not work: the
 * leftovers this list exists to catch are precisely the words that first pass
 * failed to translate, so they show up on the English side as well.
 *
 * Only diacritic-free words are kept: anything with ą/ę/ł/… is already caught
 * by a character check in the guard.
 */
import { writeFileSync } from "node:fs";
import { neon } from "@neondatabase/serverless";

const sql = neon(process.env.DATABASE_URL);

const MIN_POLISH = 5; // seen at least this often in Polish source names
// Kept unchanged in under this share of translations; brands sit near 1.0.
const MAX_KEPT_RATIO = 0.9;

function tokens(text) {
  return text.toLowerCase().match(/[a-ząćęłńóśźż]+/g) ?? [];
}

const rows = await sql.query(
  `SELECT source_text, translated_text FROM translations
   WHERE source_lang = 'pl' AND target_lang = 'en'`,
);

const pl = new Map();
const en = new Map();
for (const { source_text, translated_text } of rows) {
  for (const t of new Set(tokens(source_text))) pl.set(t, (pl.get(t) ?? 0) + 1);
  for (const t of new Set(tokens(translated_text))) en.set(t, (en.get(t) ?? 0) + 1);
}

const englishRows = await sql.query(
  `SELECT p.name, p.description FROM products p
   JOIN suppliers s ON s.id = p.supplier_id
   WHERE s.adapter_type = 'maxy_xml'`,
);
const english = new Set();
for (const { name, description } of englishRows) {
  for (const t of tokens(`${name} ${description ?? ""}`)) english.add(t);
}

const words = [...pl.entries()]
  .filter(([w, n]) =>
    n >= MIN_POLISH &&
    !/[ąćęłńóśźż]/.test(w) &&
    !english.has(w) &&
    (en.get(w) ?? 0) / n < MAX_KEPT_RATIO &&
    // One- and two-letter tokens are mostly unit and size fragments ("m",
    // "xl"); the few Polish ones that matter are listed by hand in the guard.
    w.length >= 3,
  )
  .sort((a, b) => b[1] - a[1])
  .map(([w]) => w);

writeFileSync(
  new URL("../src/lib/polish-words.mjs", import.meta.url),
  `// Generated by scripts/build-polish-wordlist.mjs — do not edit by hand.\n` +
    `// ${words.length} Polish words (no diacritics) from ${rows.length} pl -> en translations.\n` +
    `export const POLISH_VOCABULARY = new Set(${JSON.stringify(words)});\n`,
);

console.log(`${words.length} woorden uit ${rows.length} vertalingen`);
console.log("meest voorkomend:", words.slice(0, 60).join(", "));
process.exit(0);
