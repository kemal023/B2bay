/** Fills {placeholders}: fmt("Pagina {page}", { page: 2 }). */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

/** Picks the singular or plural template for a count. */
export function plural(count: number, one: string, other: string, vars: Record<string, string | number> = {}) {
  return fmt(count === 1 ? one : other, { ...vars, count });
}
